local T = require('tests/harness')
local util = require('core/util')
local settings = require('core/settings')

local function eval(src)
    local fn = assert((loadstring or load)('return ' .. src))
    return fn()
end

T.test('trim and lines handle every line ending', function()
    T.eq(util.trim('  a b \t'), 'a b')
    local lines = util.lines('one\r\ntwo\rthree\nfour')
    T.eq(#lines, 4)
    T.eq(lines[2], 'two')
    T.eq(lines[4], 'four')
end)

T.test('normalize_text removes shared indentation, tabs and blank edges', function()
    local text = util.normalize_text('\n        - first\n\t    - second   \n          indented\n    \n')
    T.eq(text, '- first\n- second\n  indented')
    T.eq(util.normalize_text('flush\n    indented'), 'flush\n    indented')
    T.eq(util.normalize_text(''), '')
end)

T.test('wrap keeps short lines and wraps long ones on words', function()
    local lines = util.wrap('short\nthe quick brown fox jumps over the lazy dog', 15)
    T.eq(lines[1], 'short')
    T.eq(lines[2], 'the quick brown')
    T.eq(lines[3], 'fox jumps over')
    T.eq(lines[4], 'the lazy dog')
end)

T.test('wrap indents continuation lines under a bullet', function()
    local lines = util.wrap('- alpha beta gamma delta epsilon', 16)
    T.eq(lines[1], '- alpha beta')
    T.eq(lines[2], '  gamma delta')
    T.eq(lines[3], '  epsilon')
    local numbered = util.wrap('12. one two three four', 12)
    T.eq(numbered[1], '12. one two')
    T.eq(numbered[2], '    three')
end)

T.test('wrap splits words longer than the width', function()
    local lines = util.wrap('abcdefghijklmnopqrstuvwxyz', 10)
    T.eq(lines[1], 'abcdefghij')
    T.eq(lines[2], 'klmnopqrst')
    T.eq(lines[3], 'uvwxyz')
end)

T.test('wrap ignores color codes when measuring and never splits them', function()
    local colored = '\\cs(255,0,0)red\\cr words here'
    T.eq(util.visible_len(colored), #'red words here')
    T.eq(#util.wrap(colored, 14), 1)
    local long = util.wrap('\\cs(1,2,3)abcdefghijklmnop\\cr', 5)
    T.eq(#long, 1, 'a colored word stays whole')
end)

T.test('wrap with width 0 never wraps', function()
    local line = string.rep('word ', 100)
    T.eq(#util.wrap(line, 0), 1)
end)

T.test('quote produces Lua literals that round-trip', function()
    for _, s in ipairs({ 'plain', 'Gu\'Dha "Effigy"', 'back\\slash', 'new\nline', 'tab\tand\r', '\0zero' }) do
        local q = util.quote(s)
        T.no(q:find('\n'), 'quoted string stays on one line')
        T.eq(eval(q), s)
    end
end)

T.test('long_string cannot be closed early by the text', function()
    for _, s in ipairs({ 'simple', 'has ]] inside', 'ends with ]', 'has ]=] and ]] both' }) do
        T.eq(eval(util.long_string(s)), s)
    end
end)

T.test('key_literal uses brackets for keywords and odd keys', function()
    T.eq(util.key_literal('fafnir'), 'fafnir')
    T.eq(util.key_literal('end'), '["end"]')
    T.eq(util.key_literal('two words'), '["two words"]')
end)

T.test('serialize round-trips nested data deterministically', function()
    local data = { auto = false, positions = { ['*'] = { x = 1, y = -2 }, boss = { x = 3.5, y = 4 } }, list = { 'a', 'b' } }
    local src = util.serialize(data)
    T.eq(src, util.serialize(eval(src)))
    local back = eval(src)
    T.eq(back.positions['*'].y, -2)
    T.eq(back.positions.boss.x, 3.5)
    T.eq(back.list[2], 'b')
    T.eq(back.auto, false)
end)

T.test('little-endian readers', function()
    local s = string.char(0x12, 0x34, 0x56, 0x78)
    T.eq(util.u16le(s, 1), 0x3412)
    T.eq(util.u32le(s, 1), 0x78563412)
    T.eq(util.u32le(s, 2), nil, 'not enough bytes')
end)

T.test('color settings accept names, hex and tables', function()
    local ok, c = settings.check('color', 'Orange')
    T.ok(ok)
    T.eq(c[1], 255)
    ok, c = settings.check('color', '#10A0ff')
    T.ok(ok)
    T.eq(c[2], 160)
    ok, c = settings.check('background', { 1, 2, 3 })
    T.eq(c[3], 3)
    ok, c = settings.check('background', { red = 9, green = 8, blue = 7 })
    T.eq(c[1], 9)
    local bad, msg = settings.check('color', 'purpleish')
    T.no(bad)
    T.has(msg, '"purpleish"')
    T.has(msg, 'not a color name')
    T.no((settings.check('color', { 300, 0, 0 })))
end)

T.test('number settings are range checked; width and max_lines allow 0', function()
    T.eq(select(2, settings.check('font_size', '14')), 14)
    T.no((settings.check('font_size', 'big')))
    T.no((settings.check('opacity', 999)))
    T.eq(select(2, settings.check('width', 0)), 0)
    T.no((settings.check('width', 5)))
    T.eq(select(2, settings.check('max_lines', 0)), 0)
    local _, msg = settings.check('opacity', -1)
    T.has(msg, 'from 0 to 255')
end)

T.test('enum, boolean, position and icon settings', function()
    T.eq(select(2, settings.check('mode', ' Combat ')), 'combat')
    local ok, msg = settings.check('mode', 'sticky')
    T.no(ok)
    T.has(msg, 'combat, manual, pinned, target')
    T.no((settings.check('close_on_zone', 'yes')))
    local p = select(2, settings.check('position', { 10.4, 20.6 }))
    T.eq(p.x, 10)
    T.eq(p.y, 21)
    T.no((settings.check('position', { x = 'left' })))
    T.eq(select(2, settings.check('icon', 'Information')), 'info')
    T.eq(select(2, settings.check('icon', 'none')), false)
    T.eq(select(2, settings.check('icon', false)), false)
    T.eq(select(2, settings.check('icon', 'my_boss.png')), 'my_boss.png')
    T.no((settings.check('icon', 42)))
    for _, path in ipairs({ '\\\\host\\share\\x.png', '//host/share/x.png', 'C:/art/x.png', '../x.png', 'sub/x.png' }) do
        local ok, msg = settings.check('icon', path)
        T.no(ok, path .. ' must be refused')
        T.has(msg, 'not a path')
    end
end)

T.test('every built-in default is valid', function()
    local d = settings.normalized_builtin()
    T.eq(d.mode, 'target')
    T.eq(d.position.x, 800)
    T.eq(#d.color, 3)
end)
